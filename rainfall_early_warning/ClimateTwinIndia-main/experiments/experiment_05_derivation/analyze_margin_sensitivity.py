def load_benchmark_index() -> dict:
    with open(BENCHMARK, "r", encoding="utf8") as f:
        benchmark = json.load(f)
    index = {}
    for q in benchmark["questions"]:
        index[q["id"]] = {
            "subcategory": q["subcategory"],
            "protocol": q["context"]["protocol"],
            "gt_metrics": q["context"]["metrics"],
            "gt_decision": q["context"]["decision"],
        }
    return index


def load_model_derivation(model: str) -> pd.DataFrame:
    path = os.path.join(RESULT_DIR, f"{model}_derivation.csv")
    if not os.path.exists(path):
        raise FileNotFoundError(path)
    return pd.read_csv(path)


# ----------------------------------------------------------
# BASELINE VALIDATION GATE
# ----------------------------------------------------------

class BaselineValidationError(RuntimeError):
    pass


def validate_baseline(bench_index: dict, model_frames: dict) -> None:
    """Before generating any sensitivity curve:

      1. alpha=0 perturbation must be the identity transform.
      2. classify_with_thresholds(GT_metrics, protocol) must reproduce
         context.decision for every question (canonical oracle sanity).
      3. classify_with_thresholds(Pred_metrics, protocol) must reproduce
         each model CSV's own RecoveredDecision / Decision_Correct.

    Raises BaselineValidationError and generates nothing if any check
    fails, per the freeze requirement: "do not generate scientific
    results from an inconsistent oracle."
    """
    failures = []

    for qid, q in bench_index.items():
        if q["subcategory"] not in SUPPORTED_SUBCATEGORIES:
            continue

        # (1) identity at alpha=0
        identity = perturb_protocol(q["protocol"], q["gt_metrics"], 0.0)
        if identity["thresholds"] != q["protocol"]["thresholds"]:
            failures.append(f"{qid}: alpha=0 is not the identity transform")

        # (2) canonical oracle reproduces the stored ground-truth decision
        recomputed_gt = classify_with_thresholds(q["gt_metrics"], q["protocol"])
        if recomputed_gt != q["gt_decision"]:
            failures.append(
                f"{qid}: canonical oracle on GT metrics gives {recomputed_gt}, "
                f"expected {q['gt_decision']}"
            )

    for model, df in model_frames.items():
        for _, row in df.iterrows():
            qid = row["id"]
            if qid not in bench_index:
                continue
            q = bench_index[qid]
            if q["subcategory"] not in SUPPORTED_SUBCATEGORIES:
                continue

            oracle_metrics = ORACLE_METRICS[q["subcategory"]]
            pred_values = [row.get(f"Pred_Metric{i+1}") for i in range(len(oracle_metrics))]
            if any(pd.isna(v) for v in pred_values):
                continue  # incomplete prediction -- excluded from the gate, same as evaluate_derivation.py's ERROR handling

            pred_metrics = {name: float(val) for name, val in zip(oracle_metrics, pred_values)}
            recomputed_pred = classify_with_thresholds(pred_metrics, q["protocol"])

            if recomputed_pred != row["RecoveredDecision"]:
                failures.append(
                    f"{model}/{qid}: canonical oracle on predicted metrics gives "
                    f"{recomputed_pred}, but {model}_derivation.csv RecoveredDecision "
                    f"is {row['RecoveredDecision']}"
                )

    if failures:
        raise BaselineValidationError(
            f"{len(failures)} baseline validation failure(s); first 10:\n"
            + "\n".join(failures[:10])
        )


