def build_question_level_records(bench_index: dict, model_frames: dict, alphas: list) -> pd.DataFrame:
    rows = []

    for model, df in model_frames.items():
        for _, row in df.iterrows():
            qid = row["id"]
            if qid not in bench_index:
                continue
            q = bench_index[qid]
            sub = q["subcategory"]

            if sub not in SUPPORTED_SUBCATEGORIES:
                # Explicitly marked, never silently skipped or approximated.
                rows.append({
                    "model": model, "question_id": qid, "category": sub,
                    "alpha": None, "status": "unsupported_protocol",
                    "reason": "subcategory not in PERTURBATION_TARGETS",
                })
                continue

            oracle_metrics = ORACLE_METRICS[sub]
            gt_values = [row.get(f"GT_Metric{i+1}") for i in range(len(oracle_metrics))]
            pred_values = [row.get(f"Pred_Metric{i+1}") for i in range(len(oracle_metrics))]

            if any(pd.isna(v) for v in pred_values):
                rows.append({
                    "model": model, "question_id": qid, "category": sub,
                    "alpha": None, "status": "insufficient_prediction",
                    "reason": "one or more predicted metrics missing/unparseable",
                })
                continue

            pred_metrics = {name: float(val) for name, val in zip(oracle_metrics, pred_values)}
            has_error = metric_error_present(gt_values, pred_values)

            baseline_recovered = row["RecoveredDecision"]
            baseline_correct = bool(row["Decision_Correct"])
            if has_error:
                baseline_status = "absorbed" if baseline_correct else "propagated"
            else:
                baseline_status = "no_error"

            for alpha in alphas:
                perturbed_protocol = perturb_protocol(q["protocol"], q["gt_metrics"], alpha)

                perturbed_gt_decision = classify_with_thresholds(q["gt_metrics"], perturbed_protocol)
                perturbed_pred_decision = classify_with_thresholds(pred_metrics, perturbed_protocol)

                if has_error:
                    # Propagation is always judged against the ORIGINAL
                    # canonical ground-truth decision. The threshold
                    # perturbation is the intervention; it must not redefine
                    # the target outcome itself. `perturbed_gt_decision` is
                    # retained above as a diagnostic for boundary collapse.
                    perturbed_absorbed = perturbed_pred_decision == q["gt_decision"]
                    perturbed_status = "absorbed" if perturbed_absorbed else "propagated"
                else:
                    perturbed_status = "no_error"

                rows.append({
                    "model": model,
                    "question_id": qid,
                    "category": sub,
                    "alpha": alpha,
                    "status": "evaluated",
                    "reason": "",
                    "original_gt_decision": q["gt_decision"],
                    "perturbed_gt_decision": perturbed_gt_decision,
                    "perturbed_pred_decision": perturbed_pred_decision,
                    "baseline_recovered_decision": baseline_recovered,
                    "baseline_status": baseline_status,
                    "perturbed_status": perturbed_status,
                    "metric_error_present": has_error,
                })

    return pd.DataFrame(rows)


# ----------------------------------------------------------
# BOOTSTRAP
# ----------------------------------------------------------

def _stable_group_seed(*parts) -> int:
    """Small deterministic FNV-1a-style hash, mirroring the codebase's
    existing stable_seed() convention (hypothesis_benchmark_generator_v2.py),
    used only to derive a per-group bootstrap seed from BOOTSTRAP_SEED.
    """
    text = "|".join(str(p) for p in parts)
    acc = 2166136261 ^ BOOTSTRAP_SEED
    for ch in text:
        acc ^= ord(ch)
        acc = (acc * 16777619) & 0xFFFFFFFF
    return acc


def propagation_rate_with_ci(statuses: list, group_key: tuple, n_resamples: int) -> dict:
    """statuses: list of 'absorbed'/'propagated' for metric-error rows in
    one (alpha, grouping) cell. Returns point estimate + bootstrap CI.
    """
    n = len(statuses)
    if n == 0:
        return {"n": 0, "propagation_rate": None, "ci_low": None, "ci_high": None}

    arr = np.array([1 if s == "propagated" else 0 for s in statuses])
    point = float(arr.mean())

    if n_resamples <= 0:
        return {"n": n, "propagation_rate": point, "ci_low": None, "ci_high": None}

    rng = np.random.RandomState(_stable_group_seed(*group_key) & 0xFFFFFFFF)
    resample_means = np.empty(n_resamples)
    for i in range(n_resamples):
        idx = rng.randint(0, n, size=n)
        resample_means[i] = arr[idx].mean()

    ci_low, ci_high = np.percentile(resample_means, [2.5, 97.5])
    return {"n": n, "propagation_rate": point, "ci_low": float(ci_low), "ci_high": float(ci_high)}


def build_aggregates(question_df: pd.DataFrame, n_resamples: int):
    err = question_df[
        (question_df["status"] == "evaluated") & (question_df["metric_error_present"])
    ].copy()

    overall_rows = []
    for alpha, g in err.groupby("alpha"):
        stats = propagation_rate_with_ci(list(g["perturbed_status"]), ("overall", alpha), n_resamples)
        overall_rows.append({"alpha": alpha, **stats})
    overall_df = pd.DataFrame(overall_rows).sort_values("alpha")

    model_rows = []
    for (model, alpha), g in err.groupby(["model", "alpha"]):
        stats = propagation_rate_with_ci(list(g["perturbed_status"]), ("model", model, alpha), n_resamples)
        model_rows.append({"model": model, "alpha": alpha, **stats})
    model_df = pd.DataFrame(model_rows).sort_values(["model", "alpha"])

    category_rows = []
    for (category, alpha), g in err.groupby(["category", "alpha"]):
        stats = propagation_rate_with_ci(list(g["perturbed_status"]), ("category", category, alpha), n_resamples)
        category_rows.append({"category": category, "alpha": alpha, **stats})
    category_df = pd.DataFrame(category_rows).sort_values(["category", "alpha"])

    return overall_df, model_df, category_df


