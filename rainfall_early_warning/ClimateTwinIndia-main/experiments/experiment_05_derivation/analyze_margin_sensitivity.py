#!/usr/bin/env python3
"""
===========================================================
ClimateTwinBench -- Offline Decision-Margin Sensitivity Analysis
(Phase 1.5D follow-up experiment)
===========================================================

WHAT THIS SCRIPT DOES
----------------------
For every canonical (model, question) observation in the existing
Experiment 5 derivation results:

  1. Holds the model's OBSERVED predicted metrics completely fixed
     (no new inference, no re-parsing of raw model text).
  2. Holds the ground-truth metrics completely fixed.
  3. Systematically perturbs only the deterministic decision-boundary
     THRESHOLDS in `context.protocol`, using a fixed, pre-registered
     family of transformations (see `perturb_protocol` below).
  4. Re-runs the existing canonical oracle, `classify_with_thresholds()`
     (imported, never reimplemented -- src/hypothesis_benchmark_generator_v2.py),
     on the perturbed thresholds.
  5. Records whether each observed metric error is ABSORBED (recovered
     decision still matches ground truth) or PROPAGATED (recovered
     decision now diverges) at every perturbation level.

This is a 100% offline analysis:
  - no model API calls
  - no prompt changes
  - no changes to benchmark/ClimateTwinBench_Hypothesis_V2.json
  - no changes to evaluate_derivation.py or classify_with_thresholds()
  - no changes to any existing results/*.csv

PERTURBATION DEFINITION (fixed BEFORE any outcome was inspected)
------------------------------------------------------------------
For a subcategory's protocol, `classify_with_thresholds()` compares a
small, fixed set of (metric, threshold) pairs (see PERTURBATION_TARGETS
below -- mirrors, but does not reimplement, the boolean logic at
src/hypothesis_benchmark_generator_v2.py lines 243-320). For every such
pair, and a scalar tightening parameter alpha:

    T'(alpha) = T + alpha * (GT_metric - T)

    alpha = 0    -> T' = T                  (identity / baseline)
    alpha = 1    -> T' = GT_metric           (threshold collapses onto
                                              the canonical ground-truth
                                              value: zero decision margin)

PRIMARY DOMAIN: alpha in [0, 1]. This is the entire scientific
intervention -- "fraction of the canonical GT-to-threshold margin
closed" -- and the default ALPHA_SCHEDULE below never leaves it.
alpha > 1 (overshooting past the GT value) is a qualitatively different
geometry -- the threshold inverts past the point that used to be
canonically correct -- and is deliberately NOT part of this experiment;
it is never generated by default and is not treated as "more
tightening." A caller may still pass an out-of-[0,1] value via
`--alphas` for one-off, explicitly-requested exploration (e.g. negative
alpha as a margin-RELAXATION probe); the script warns when this happens
and such runs are not the primary curve.

alpha is dimensionless: it is the fraction of the *canonical* GT-to-
threshold gap that has been closed. It requires no IQR / percentile
normalization (unlike a cross-category slack comparison), because it is
defined relative to each pair's own baseline margin. This sidesteps the
IQR-availability gaps that block category-comparable slack metrics for
some subcategories (spatial_coherence's un-persisted raw distributions,
reliability_aware's missing global-completeness p75, persistent's two
fixed-constant thresholds) -- none of those are needed here, because we
never need to compare absolute margins across categories, only the
fraction of each question's own margin that has been closed.

The perturbation only ever touches `context.protocol.thresholds` on an
in-memory deep copy. GT metrics, predicted metrics, and the canonical
benchmark/evaluator files are never modified.

SCIENTIFIC INTEGRITY
---------------------
- The (metric, threshold) pairs eligible for perturbation are a FIXED
  per-subcategory structural mapping (PERTURBATION_TARGETS), derived
  once from reading classify_with_thresholds()'s source, identical for
  every question of that subcategory. They do not depend on the
  question, the model, or the outcome.
- The magnitude of movement at each alpha depends only on the canonical
  threshold and the canonical ground-truth metric -- never on the
  predicted metric and never on whether the resulting classification is
  absorbed or propagated. There is no dependence, direct or indirect, on
  the outcome being measured.
- The alpha schedule (ALPHA_SCHEDULE) is fixed in this file before any
  sensitivity curve is computed.
- The script is a pure function of its inputs: run twice, same output
  (see tests: test_deterministic_repeated_execution).

USAGE
-----
    python analyze_margin_sensitivity.py
    python analyze_margin_sensitivity.py --alphas 0,0.25,0.5,0.75,1.0
    python analyze_margin_sensitivity.py --bootstrap 500
===========================================================
"""

