# ----------------------------------------------------------
# CORE TRANSFORM
# ----------------------------------------------------------

def perturb_protocol(protocol: dict, gt_metrics: dict, alpha: float) -> Optional[dict]:
    """Return a deep-copied, perturbed protocol at tightening level `alpha`.

    Returns None if the protocol's subcategory is not in
    PERTURBATION_TARGETS (unsupported -- see module docstring; in the
    current benchmark this never happens, since all six shipped
    subcategories are supported, but the check is kept so a future
    seventh subcategory fails loud rather than silently).
    """
    sub = protocol["subcategory"]
    if sub not in PERTURBATION_TARGETS:
        return None

    new_protocol = copy.deepcopy(protocol)
    t = new_protocol["thresholds"]

    for metric_key, threshold_key in PERTURBATION_TARGETS[sub]:
        if metric_key not in gt_metrics or threshold_key not in t:
            # Defensive only -- would indicate a benchmark/protocol
            # mismatch with PERTURBATION_TARGETS, not an expected path.
            continue
        T = float(t[threshold_key])
        G = float(gt_metrics[metric_key])
        t[threshold_key] = T + alpha * (G - T)

    return new_protocol


def metric_error_present(gt_values: list, pred_values: list, atol: float = METRIC_TOLERANCE) -> bool:
    """Mirrors paper_statistics.py's metric_correct(): a metric slot with
    no ground truth (None/NaN) is skipped; a missing prediction where GT
    exists counts as an error; otherwise compares with atol tolerance.
    """
    for gt, pred in zip(gt_values, pred_values):
        if gt is None or (isinstance(gt, float) and np.isnan(gt)):
            continue
        if pred is None or (isinstance(pred, float) and np.isnan(pred)):
            return True
        if not np.isclose(float(gt), float(pred), atol=atol):
            return True
    return False


